import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {normalizeEnvironment,withEnvironmentPreset} from '../assets/grim-158/environment-state.js';
const root=new URL('../assets/grim-158/',import.meta.url);
const env=normalizeEnvironment({cinematicPan:true,cinematicSpeed:25});
assert.equal(env.cinematicPan,true);
assert.equal(env.cinematicSpeed,2.5);
assert.equal(normalizeEnvironment({cinematicSpeed:-2}).cinematicSpeed,.35);
assert.equal(normalizeEnvironment({}).cinematicPan,false,'New sessions keep the intentional opt-in default');
const switched=withEnvironmentPreset({cinematicPan:true,cinematicSpeed:1.8,seed:123},'Forest');
assert.equal(switched.cinematicPan,true,'Terrain presets must not disable cinematic camera');
assert.equal(switched.cinematicSpeed,1.8,'Terrain presets must not change cinematic speed');
assert.equal(switched.seed,123,'Terrain presets must preserve the seed');
assert.equal(switched.ground,'grass');
assert.equal(withEnvironmentPreset({cinematicPan:false},'Snowfield').cinematicPan,false,'Manual OFF must remain OFF');
const world=readFileSync(new URL('world.js',root),'utf8');
const stage=readFileSync(new URL('stage.js',root),'utf8');
const editor=readFileSync(new URL('environment-editor.js',root),'utf8');
const ui=readFileSync(new URL('../index.html',import.meta.url),'utf8');
for(const s of ['function cinematicStep(', 'updateCinematicSettings(env)', 'getCinematic()', 'cinematicPauseUntil', 'nativeCards.update(', 'createNativeCardLayer('])assert(world.includes(s),`Missing camera or depth fix: ${s}`);
assert(!world.includes('canvas.toDataURL('),'Old animated PNG masks must not return');
assert(world.includes('if(environmentMoving||transition||(cinematicEnabled&&!reducedMotion)||cardFxMoving)'),'Reduced-motion viewers must not schedule perpetual camera frames');
assert(stage.includes("const autoPanButton=$('autoPanToggle')"));
assert(ui.includes('id="autoPanToggle"')&&editor.includes('data-env="cinematicPan"'));
console.log('PASS: cinematic camera state/controls, native 3D occlusion and regression guards.');
