import assert from 'node:assert/strict';
import * as T from '../assets/grim-1413/vendor/three.module.js';
import {createNativeCardLayer,cardVisualData,damageSeverity,shatterProgress} from '../assets/grim-1413/native-cards.js';
import {readFileSync} from 'node:fs';

const ctx={clearRect(){},setTransform(){},save(){},restore(){},beginPath(){},moveTo(){},lineTo(){},quadraticCurveTo(){},closePath(){},fill(){},stroke(){},clip(){},fillRect(){},fillText(){},drawImage(){},createLinearGradient(){return {addColorStop(){}}},measureText(t){return {width:String(t).length*7}}};
globalThis.document={createElement(type){assert.equal(type,'canvas');return {width:0,height:0,getContext(){return ctx;}}}};
const stateSource=readFileSync(new URL('../assets/grim-1413/state.js',import.meta.url),'utf8');
assert(stateSource.includes("'Burning','Frozen'"),'DM can apply both finish conditions');
assert.equal(damageSeverity(1),0);assert.equal(damageSeverity(.79)>0,true);
assert(damageSeverity(.15)>damageSeverity(.50));assert.equal(damageSeverity(0),1);
assert.equal(shatterProgress(0),0);assert.equal(shatterProgress(1350),1);
const place={side:'player',active:false,rank:1,scale:.72};
const makeCharacter=hp=>({id:'hero',name:'Frost & Flame',hp,maxHp:40,conditions:['Burning 2','Frozen'],ac:18,level:5,initiative:19});
assert.equal(cardVisualData(makeCharacter(40),place,true).burning,true);
assert.equal(cardVisualData(makeCharacter(40),place,true).frozen,true);
const scene=new T.Scene(),layer=createNativeCardLayer(scene);
const anchors=[{id:'hero',x:2,z:4,active:false,layout:place}];
layer.setCards(anchors,[makeCharacter(12)],true);
assert.equal(layer.entries.get('hero').shatter,null,'No shatter on first appearance');
layer.setCards(anchors,[makeCharacter(0)],true);
const entry=layer.entries.get('hero');
assert(entry.shatter,'Live transition to zero HP starts a one-shot 3D shatter');
assert.equal(entry.shatter.shards.length,24,'Shatter uses 24 texture-mapped 3D triangles');
assert(layer.needsAnimation(entry.shatter.start+100),'Shatter schedules animation frames');
const camera=new T.PerspectiveCamera(42,16/9,.1,140);camera.position.set(0,12,28);camera.lookAt(0,0,0);camera.updateMatrixWorld();
const env={terrainWidth:32,terrainDepth:20,seed:123,variation:.3,hills:'flat'};
layer.update(camera,1600,900,env,()=>0,entry.shatter.start+350);
assert(entry.shatter.shards.some(s=>s.mesh.position.x!==s.x||s.mesh.position.y!==s.y),'Physical fragments move off the card');
layer.setCards(anchors,[makeCharacter(5)],true);
assert.equal(entry.shatter,null,'Revival immediately clears any shatter debris');
layer.setCards(anchors,[makeCharacter(0)],true);
layer.update(camera,1600,900,env,()=>0,entry.shatter.start+2000);
assert.equal(entry.shatter,null,'Finished shatter disposes GPU fragments');
layer.dispose();
const world=readFileSync(new URL('../assets/grim-1413/world.js',import.meta.url),'utf8');
assert(world.includes('cardFxMoving=nativeCards.needsAnimation(t)'),'Camera renderer continues while card effects animate');
console.log('PASS: continuous HP severity, status stacking, one-shot textured shatter, revival and GPU cleanup.');
