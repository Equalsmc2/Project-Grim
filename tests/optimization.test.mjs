import assert from 'node:assert/strict';
import {readFileSync,existsSync,readdirSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const active=path.join(root,'assets/grim-144');
const stage=readFileSync(path.join(active,'stage.js'),'utf8');
const world=readFileSync(path.join(active,'world.js'),'utf8');
const index=readFileSync(path.join(root,'index.html'),'utf8');
const dm=readFileSync(path.join(root,'dm.html'),'utf8');
assert(index.includes('grim-144/stage.js')&&dm.includes('grim-144/dm.js'),'Both pages load the active bundle');
assert(readdirSync(path.join(root,'assets')).every(x=>x==='grim-144'||x==='audio'),'Only the active asset directory and five on-demand audio files are shipped');
assert(world.includes('if(projectionDirty){projectCards();projectionDirty=false;}'),'Weather frames do not repeatedly rewrite card DOM');
assert(world.includes('cardElements.get(a.id)'),'Projection reuses cached card nodes');
assert(world.includes('cardPoint.set(a.x,y+hover,a.z)'),'Distance calculations reuse vector rather than allocate per frame');
assert(world.includes('Math.sqrt(2800000/(width*height))'),'GPU resolution budget is in place');
assert(stage.includes('if(tiltFrame)return'),'Pointer events are throttled to one frame');
assert(world.includes('document.hidden')&&world.includes('clearRoot()'),'Existing hidden-tab and resource cleanup are retained');
for(const f of ['state.js','formation.js','world.js','firebase-sync.js','environment-editor.js','vendor/three.module.js'])assert(existsSync(path.join(active,f)),`${f} is present`);
console.log('PASS: active assets only; cache-safe entry points; renderer/card optimizations; resource lifecycle; UI throttling.');
