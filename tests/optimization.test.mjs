import assert from 'node:assert/strict';
import {readFileSync,existsSync,readdirSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const active=path.join(root,'assets/grim-158');
const stage=readFileSync(path.join(active,'stage.js'),'utf8');
const world=readFileSync(path.join(active,'world.js'),'utf8');
const index=readFileSync(path.join(root,'index.html'),'utf8');
const dm=readFileSync(path.join(root,'dm.html'),'utf8');
assert(index.includes('grim-158/stage.js')&&dm.includes('grim-158/dm.js'),'Both pages load the active bundle');
const bundles=readdirSync(path.join(root,'assets')).filter(name=>/^(?:grim-|battlefield-)/.test(name) && name!=='grim-158');
assert(bundles.every(name=>![index,dm,stage,world].some(text=>text.includes('assets/'+name+'/')||text.includes('../'+name+'/'))),'Live website must not reference historical asset bundles');
assert(world.includes('if(projectionDirty){projectCards(t);projectionDirty=false;}'),'Weather frames do not repeatedly rewrite card DOM');
assert(world.includes('nativeCards.update(camera,width,height,env,landscapeHeight,time,fitScale)'),'Card geometry follows the 3D camera');
assert(world.includes('nativeCards.dispose()'),'Native card GPU resources are released');
assert(world.includes('graphicsPixelRatio(quality,width,height') && existsSync(path.join(active,'graphics-quality.js')),'Configurable GPU pixel budget is in place');
assert(stage.includes('if(tiltFrame)return'),'Pointer events are throttled to one frame');
assert(world.includes('document.hidden')&&world.includes('disposeObject(root);scene.remove(root)'),'Hidden-tab pause and root cleanup are retained');
for(const f of ['state.js','formation.js','world.js','native-cards.js','firebase-sync.js','environment-editor.js','vendor/three.module.js'])assert(existsSync(path.join(active,f)),`${f} is present`);
console.log('PASS: active assets only; cache-safe entry points; renderer/card optimizations; resource lifecycle; UI throttling.');
